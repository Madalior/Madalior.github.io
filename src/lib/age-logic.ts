export function calculateAge(dobStr: string, cutoffDateStr: string) {
  const dob = new Date(dobStr);
  const cutoff = new Date(cutoffDateStr);

  let years = cutoff.getFullYear() - dob.getFullYear();
  let months = cutoff.getMonth() - dob.getMonth();
  let days = cutoff.getDate() - dob.getDate();

  if (days < 0) {
    months--;
    const prevMonth = new Date(cutoff.getFullYear(), cutoff.getMonth(), 0);
    days += prevMonth.getDate();
  }
  
  if (months < 0) {
    years--;
    months += 12;
  }
  
  return { years, months, days };
}

export function checkEligibility(age: { years: number, months: number, days: number }, examName: string, category: string) {
  const exam = EXAMS[examName as keyof typeof EXAMS];
  const maxAllowed = exam.maxAge[category as keyof typeof exam.maxAge];

  const eligible = age.years >= exam.minAge && age.years <= maxAllowed;

  return {
    eligible,
    maxAllowed,
  };
}
